"""Measure cipher speed and run NistRng's SP 800-22-style tests."""

from __future__ import annotations

import argparse
import json
from time import perf_counter

from stream_cipher import keystream, xor_bytes


def benchmark_cipher(
    size: int = 256 * 1024,
    chunk_size: int = 64 * 1024,
    media_bitrate_mbps: float = 2.0,
) -> dict[str, float | int]:
    if size <= 0 or chunk_size <= 0 or media_bitrate_mbps <= 0:
        raise ValueError("benchmark inputs must be positive")
    data = bytes((index * 31) & 0xFF for index in range(size))
    latencies = []
    for offset in range(0, size, chunk_size):
        started = perf_counter()
        xor_bytes(data[offset : offset + chunk_size], 0xACE1, offset)
        latencies.append(perf_counter() - started)
    elapsed = sum(latencies)
    throughput = size * 8 / elapsed / 1_000_000
    return {
        "bytes": size,
        "chunks": len(latencies),
        "elapsed_seconds": elapsed,
        "mean_chunk_latency_ms": elapsed / len(latencies) * 1000,
        "throughput_mbps": throughput,
        "media_bitrate_mbps": media_bitrate_mbps,
        "headroom_ratio": throughput / media_bitrate_mbps,
    }


def nist_report(
    byte_count: int = 128 * 1024,
    test_names: tuple[str, ...] | None = None,
) -> list[dict[str, float | str | None]]:
    if byte_count <= 0:
        raise ValueError("byte_count must be positive")
    return nist_report_for_bytes(keystream(byte_count, 0xACE1), test_names)


def nist_report_for_bytes(
    data: bytes,
    test_names: tuple[str, ...] | None = None,
) -> list[dict[str, float | str | None]]:
    """Run the selected NistRng tests on already-generated bytes."""
    if not data:
        raise ValueError("data must not be empty")
    import numpy
    from nistrng import SP800_22R1A_BATTERY, pack_sequence, run_by_name_battery

    names = test_names or tuple(SP800_22R1A_BATTERY)
    unknown = set(names) - set(SP800_22R1A_BATTERY)
    if unknown:
        raise ValueError(f"unknown NistRng tests: {', '.join(sorted(unknown))}")
    # NistRng returns int8 bits; wider integers prevent cumulative-sum overflow on NumPy 2.
    bits = pack_sequence(
        numpy.frombuffer(data, dtype=numpy.uint8)
    ).astype(numpy.int64)
    report = []
    for name in names:
        outcome = run_by_name_battery(name, bits, SP800_22R1A_BATTERY, True)
        if outcome is None:
            report.append({"name": name, "status": "inapplicable", "score": None, "elapsed_ms": 0.0})
            continue
        result, elapsed = outcome
        report.append(
            {
                "name": name,
                "status": "passed" if result.passed else "failed",
                "score": result.score,
                "elapsed_ms": float(elapsed),
            }
        )
    return report


def main() -> None:
    from nistrng import SP800_22R1A_BATTERY
    from tools.compare_variants import compare

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bytes", type=int, default=128 * 1024, dest="byte_count")
    parser.add_argument("--chunk-size", type=int, default=64 * 1024)
    parser.add_argument("--media-bitrate", type=float, default=2.0, dest="media_bitrate")
    parser.add_argument("--tests", nargs="*", help="NistRng test names; default: complete battery")
    args = parser.parse_args()

    selected_tests = tuple(args.tests) if args.tests else None
    output = {
        "warning": "Statistical test results do not establish cryptographic security.",
        "benchmark": benchmark_cipher(args.byte_count, args.chunk_size, args.media_bitrate),
        "nist_sp800_22": nist_report(args.byte_count, selected_tests),
        "generator_comparison": compare(
            args.byte_count,
            selected_tests or tuple(SP800_22R1A_BATTERY),
        ),
    }
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
